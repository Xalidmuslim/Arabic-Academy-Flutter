import java.util.Properties

plugins {
    id("com.android.application")
    id("kotlin-android")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

// Firebase remains optional. An owner's real configuration activates resource
// generation needed by background FCM; unconfigured offline builds stay valid.
if (file("google-services.json").exists()) {
    apply(plugin = "com.google.gms.google-services")
}

val ownerSigningFile = rootProject.file("key.properties")
val ownerSigning = Properties()
if (ownerSigningFile.exists()) {
    ownerSigningFile.inputStream().use { ownerSigning.load(it) }
}
val requiresOwnerSignature = System.getenv("BAYNA_REQUIRE_RELEASE_SIGNING") == "true"
if (requiresOwnerSignature && !ownerSigningFile.exists()) {
    throw GradleException("Production signing requires the owner's ignored android/key.properties and keystore.")
}

android {
    namespace = "com.example.arabic_academy"
    compileSdk = flutter.compileSdkVersion
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }

    kotlinOptions {
        jvmTarget = JavaVersion.VERSION_11.toString()
    }

    defaultConfig {
        // Keep the package ID generated by every previously shipped CI APK.
        applicationId = "com.example.arabic_academy"
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        minSdk = flutter.minSdkVersion
        targetSdk = flutter.targetSdkVersion
        versionCode = flutter.versionCode
        versionName = flutter.versionName
    }

    signingConfigs {
        getByName("debug") {
            // Created by scripts/prepare_signing.sh; never stored in Git.
            storeFile = rootProject.file("../build/signing/debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        if (ownerSigningFile.exists()) {
            create("ownerRelease") {
                storeFile = rootProject.file(ownerSigning.getProperty("storeFile"))
                storePassword = ownerSigning.getProperty("storePassword")
                keyAlias = ownerSigning.getProperty("keyAlias")
                keyPassword = ownerSigning.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8 shrinks and optimizes Java/Kotlin code; the Android resource
            // shrinker removes unreachable resources from the release package.
            // Keep native OCR JNI bindings and Flutter plugin rules intact.
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            signingConfig = signingConfigs.getByName(if (ownerSigningFile.exists()) "ownerRelease" else "debug")
        }
    }
}

