begin;
create function pg_temp.check(ok boolean,label text) returns void language plpgsql as $$begin if ok is distinct from true then raise exception 'Assertion failed: %',label;end if;end$$;
create function pg_temp.denied(q text,state text,label text) returns void language plpgsql as $$begin
 begin execute q; exception when others then if sqlstate=state then return;end if;raise exception '% unexpected %: %',label,sqlstate,sqlerrm;end;
 raise exception 'Expected rejection: %',label;end$$;
grant execute on function pg_temp.check(boolean,text),pg_temp.denied(text,text,text) to authenticated,service_role;
create policy fixture_broad_storage on storage.objects for all to authenticated using(true) with check(true);
grant insert on storage.objects to authenticated;
insert into auth.users values('10000000-0000-0000-0000-000000000001','{}'),('10000000-0000-0000-0000-000000000002','{}');
set local request.jwt.claim.sub='10000000-0000-0000-0000-000000000001';
set local role authenticated;
select pg_temp.denied('select public.save_profile(''Name'',false)','42501','profile consent mandatory');
select public.save_profile('Name',true);
select pg_temp.check((select consent_at is not null from public.profiles where id=auth.uid()),'server profile consent time');
select pg_temp.denied('update public.profiles set consent_at=now()','42501','client cannot forge consent time');
select pg_temp.denied('select public.prepare_media_upload(null,''application/pdf'',10,false)','42501','student audio only');
select pg_temp.denied('select public.prepare_media_upload(null,''audio/mp4'',10,true)','42501','global STT consent required');
update public.user_settings set stt_consent=true where user_id=auth.uid();
select public.prepare_media_upload(null,'audio/mp4',10,true);
select pg_temp.check((select count(*)=0 from public.media),'pending upload not readable');
select public.register_push_token('push-token-fixture-one');
select public.register_push_token('push-token-fixture-one');
select pg_temp.check((select count(*)=1 from public.push_tokens),'push register idempotent');
reset role;
-- Metadata fixtures emulate authoritative Storage records, not user-supplied completion flags.
select pg_temp.check((select count(*)=1 from public.media),'media registered');
select pg_temp.check(not has_function_privilege('authenticated','public.finalize_media_upload(uuid,uuid)','execute'),'client cannot finalize with forged metadata');
set local role service_role;
select pg_temp.denied('select public.finalize_media_upload((select id from public.media limit 1),''10000000-0000-0000-0000-000000000001'')','55000','missing object fails closed');
insert into storage.objects(id,bucket_id,name,metadata) select gen_random_uuid(),bucket_id,object_path,'{"size":9,"mimetype":"audio/mp4"}' from private.media_objects;
select pg_temp.denied('select public.finalize_media_upload((select id from public.media limit 1),''10000000-0000-0000-0000-000000000001'')','42501','actual size mismatch');
update storage.objects set metadata='{"size":10,"mimetype":"audio/mp4"}';
select pg_temp.denied('select public.finalize_media_upload((select id from public.media limit 1),''10000000-0000-0000-0000-000000000002'')','42501','finalization actor bound');
select public.finalize_media_upload((select id from public.media limit 1),'10000000-0000-0000-0000-000000000001');
reset role;
set local role authenticated;
select pg_temp.check((select count(*)=1 from public.media),'completed media readable');
select pg_temp.check((select count(*)=0 from storage.objects),'restrictive guard defeats broad existing read policy');
select pg_temp.denied('insert into storage.objects(id,bucket_id,name) values(gen_random_uuid(),''student-media'',''forged'')','42501','restrictive guard defeats broad existing upload policy');
select public.media_access((select id from public.media limit 1),true);
select public.reserve_stt_request((select id from public.media limit 1)) from generate_series(1,5);
select pg_temp.denied('select public.reserve_stt_request((select id from public.media limit 1))','54000','STT server rate limit');
select public.set_media_stt_consent((select id from public.media limit 1),false);
select pg_temp.denied('select public.media_access((select id from public.media limit 1),true)','42501','per-recording consent revoked');
reset role;
set local request.jwt.claim.sub='10000000-0000-0000-0000-000000000002';
set local role authenticated;
select pg_temp.check((select count(*)=0 from public.media),'another student cannot see media');
select pg_temp.check((select count(*)=0 from public.push_tokens),'another student cannot see push bindings');
select pg_temp.denied('select public.register_push_token(''push-token-fixture-one'')','42501','push token cannot be stolen');
reset role;
set local role service_role;
select public.mark_media_deleted((select id from public.media limit 1),'10000000-0000-0000-0000-000000000001');
